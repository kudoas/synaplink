import React from 'react';
import { act, renderHook, render, cleanup } from '@testing-library/react';
import { afterEach, it, expect, vi } from 'vitest';
import { EditorView } from '@codemirror/view';
import { undo } from '@codemirror/commands';
import { useAutosavedDocument } from '@audit/use-autosaved-document';
import { MemoEditor } from '@audit/components/MemoEditor';
vi.mock('@tauri-apps/plugin-opener',()=>({openUrl:vi.fn()}));
afterEach(()=>{cleanup();vi.useRealTimers();});
it('later edit remains dirty after 10 seconds following slow onSaved',async()=>{
vi.useFakeTimers();
let finish!:()=>void;
const pending=new Promise<void>(resolve=>{finish=resolve;});
const persist=vi.fn().mockImplementation(async (doc)=>({status:'saved',document:{...doc,revision:'r2'}}));
const {result}=renderHook(()=>useAutosavedDocument({persist,onSaved:()=>pending,mergeSaved:(local,saved)=>({...local,revision:saved.revision}),onError:vi.fn()}));
act(()=>result.current.load({body:'old',revision:'r1'}));
act(()=>result.current.edit(doc=>({...doc,body:'first'})));
await act(async()=>{await vi.advanceTimersByTimeAsync(700)});
expect(persist).toHaveBeenCalledTimes(1);
act(()=>result.current.edit(doc=>({...doc,body:'second'})));
await act(async()=>{await vi.advanceTimersByTimeAsync(700)});
await act(async()=>{finish();await Promise.resolve()});
await act(async()=>{await vi.advanceTimersByTimeAsync(10000)});
expect(result.current.document?.body).toBe('second');
expect(result.current.saveState).toBe('dirty');
expect(persist).toHaveBeenCalledTimes(1);
console.log('CONFIRMED: second edit remains dirty after 10s; only first edit persisted');
});
it('undo after external synchronization emits the previous body as a user change',()=>{
const onChange=vi.fn();
const props={onChange,onNavigateBackward:vi.fn(),onOpenLink:vi.fn()};
const {container,rerender}=render(<MemoEditor {...props} value='old disk body'/>);
const view=EditorView.findFromDOM(container.querySelector('.cm-editor')! as HTMLElement)!;
rerender(<MemoEditor {...props} value='new external body'/>);
expect(onChange).not.toHaveBeenCalled();
act(()=>{undo(view)});
expect(view.state.doc.toString()).toBe('old disk body');
expect(onChange).toHaveBeenCalledWith('old disk body');
console.log('CONFIRMED: undo external refresh emits old disk body as a user edit');
});
it('unmount before debounce does not persist unsaved edits',async()=>{
vi.useFakeTimers();const persist=vi.fn();
const {result,unmount}=renderHook(()=>useAutosavedDocument({persist,mergeSaved:(local)=>local,onError:vi.fn()}));
act(()=>result.current.load({body:'old',revision:'r1'}));
act(()=>result.current.edit(doc=>({...doc,body:'lost'})));
unmount();
await vi.advanceTimersByTimeAsync(1000);
expect(persist).not.toHaveBeenCalled();
console.log('CONFIRMED: unmount cancels debounce without saving');
});
