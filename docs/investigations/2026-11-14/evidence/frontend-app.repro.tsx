import { act, fireEvent, render, screen, cleanup } from '@testing-library/react';
import { afterEach, it, expect, vi } from 'vitest';
import { App } from '@audit/App';
import { api } from '@audit/api';
vi.mock('@audit/api',()=>({api:{getVault:vi.fn(),listNotes:vi.fn(),chooseVault:vi.fn(),setVault:vi.fn(),readNote:vi.fn(),saveNote:vi.fn(),createNote:vi.fn(),deleteNote:vi.fn()}}));
vi.mock('@tauri-apps/plugin-opener',()=>({openUrl:vi.fn()}));
afterEach(()=>{cleanup();vi.useRealTimers();vi.resetAllMocks()});
const old={id:'old.txt',title:'old vault secret',preview:'old',revision:'r1',modifiedAt:1,links:[]};
const fresh={id:'new.txt',title:'new vault memo',preview:'new',revision:'r1',modifiedAt:1,links:[]};
it('late old-vault polling replaces new-vault notes',async()=>{
vi.useFakeTimers();
let resolvePoll!:(value:unknown)=>void;
const pendingPoll=new Promise(resolve=>{resolvePoll=resolve});
vi.mocked(api.getVault).mockResolvedValue('/vault-old');
vi.mocked(api.listNotes).mockResolvedValueOnce([old]).mockReturnValueOnce(pendingPoll as any).mockResolvedValue([fresh]);
vi.mocked(api.chooseVault).mockResolvedValue('/vault-new');
vi.mocked(api.setVault).mockResolvedValue(undefined);
await act(async()=>{render(<App/>)});
expect(screen.getByText('old vault secret')).toBeTruthy();
await act(async()=>{await vi.advanceTimersByTimeAsync(2500)});
await act(async()=>{fireEvent.click(screen.getByTitle('保存先を変更'))});
expect(screen.getByText('new vault memo')).toBeTruthy();
expect(screen.getByTitle('/vault-new')).toBeTruthy();
await act(async()=>{resolvePoll([old]);await Promise.resolve()});
expect(screen.getByText('old vault secret')).toBeTruthy();
expect(screen.queryByText('new vault memo')).toBeNull();
expect(screen.getByTitle('/vault-new')).toBeTruthy();
});
it('save failure after external deletion blocks note selection and vault change',async()=>{
vi.useFakeTimers();
const note={...old,body:'content'};
vi.mocked(api.getVault).mockResolvedValue('/vault-old');
vi.mocked(api.listNotes).mockResolvedValueOnce([old,fresh]).mockResolvedValue([fresh]);
vi.mocked(api.readNote).mockResolvedValue(note);
vi.mocked(api.saveNote).mockRejectedValue(new Error('メモを読み込めません: No such file or directory'));
await act(async()=>{render(<App/>)});
await act(async()=>{fireEvent.click(screen.getByRole('button',{name:/old vault secret/}))});
await act(async()=>{await vi.advanceTimersByTimeAsync(2500)});
expect(screen.queryByRole('button',{name:/old vault secret/})).toBeNull();
expect(screen.getByDisplayValue('old vault secret')).toBeTruthy();
act(()=>fireEvent.change(screen.getByLabelText('タイトル'),{target:{value:'unsaved local edit'}}));
await act(async()=>{await vi.advanceTimersByTimeAsync(700)});
expect(screen.getByText('保存エラー')).toBeTruthy();
vi.mocked(api.readNote).mockClear();
await act(async()=>{fireEvent.click(screen.getByRole('button',{name:/new vault memo/}))});
expect(api.readNote).not.toHaveBeenCalled();
expect(screen.getByDisplayValue('unsaved local edit')).toBeTruthy();
await act(async()=>{fireEvent.click(screen.getByTitle('保存先を変更'))});
expect(api.chooseVault).not.toHaveBeenCalled();
expect(screen.queryByRole('button',{name:/破棄|別名|コピー|再試行/})).toBeNull();
});
